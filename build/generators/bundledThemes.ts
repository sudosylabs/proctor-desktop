import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Generator } from './registry.ts';
import { build } from 'esbuild';

const output = 'src/prctr/platform/theme/common/bundledThemeResources.generated.ts';
const snapshotsOutput = 'src/prctr/platform/theme/common/bundledThemeSnapshots.generated.ts';
export const bundledThemesGenerator: Generator = {
	id: 'theme.resources',
	inputs: ['resources/themes', 'src/prctr/platform/theme/common', 'src/prctr/base/common'],
	committedOutputs: [output, snapshotsOutput],
	buildOutputs: [],
	async generate(repository, outputRoot) {
		const source: { sha256: Record<string, string> } = JSON.parse(
			repository.read('resources/themes/github-source.json')
		);
		const resources: Record<string, string> = {};
		for (const path of repository
			.files()
			.filter((path) => path.startsWith('resources/themes/github/') && path.endsWith('.json'))
			.sort()) {
			const content = repository.read(path);
			if (
				createHash('sha256').update(content).digest('hex') !==
				source.sha256[path.slice('resources/themes/github/'.length)]
			)
				throw new Error(`Bundled theme digest mismatch: ${path}`);
			resources[path.slice('resources/themes/'.length)] = content;
		}
		const destination = join(outputRoot, output);
		mkdirSync(dirname(destination), { recursive: true });
		writeFileSync(
			destination,
			'// Generated by theme.resources. Do not edit.\n/*! @license GitHub Theme\n' +
				repository.read('resources/themes/github/LICENSE') +
				'\n*/\nexport const bundledThemeResources: Readonly<Record<string, string>> = ' +
				JSON.stringify(resources, null, '\t') +
				';\n'
		);
		// Compile the admitted source rather than maintaining a second theme parser.
		const bundled = await build({
			entryPoints: ['src/prctr/platform/theme/common/packagedThemeLoader.ts'],
			bundle: true,
			write: false,
			format: 'esm',
			platform: 'node',
			target: 'node24',
			tsconfig: 'build/tsconfig.platform-foundation.json'
		});
		const module = (await import(
			`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0]!.text).toString('base64')}`
		)) as {
			prepareThemeSnapshots(
				resources: Readonly<Record<string, string>>
			): Promise<Record<string, string>>;
		};
		const snapshots = await module.prepareThemeSnapshots(resources);
		writeFileSync(
			join(outputRoot, snapshotsOutput),
			'// Generated by theme.resources through the complete upstream theme loader. Do not edit.\n/*! @license GitHub Theme\n' +
				repository.read('resources/themes/github/LICENSE') +
				'\n*/\n' +
				'export const bundledThemeSnapshots: Readonly<Record<string, string>> = ' +
				JSON.stringify(snapshots, null, '\t') +
				';\n'
		);
	}
};
