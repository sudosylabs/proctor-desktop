import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import ts from 'typescript';
import type { Generator } from './registry.ts';

const input = 'resources/server-api/openapi.json';
const types = 'src/prctr/platform/serverApi/common/serverApi.generated.ts';
const contract = 'src/prctr/platform/serverApi/node/serverContract.generated.ts';
const inventory = 'resources/server-api/coverage.generated.json';
export const serverApiGenerator: Generator = {
	id: 'server.api',
	inputs: [input, 'resources/server-api/source.json', 'build/generators/serverApi.ts'],
	committedOutputs: [types, contract, inventory],
	buildOutputs: [],
	async generate(repository, outputRoot) {
		const source = repository.read(input);
		const provenance = JSON.parse(repository.read('resources/server-api/source.json')) as {
			sha256: string;
		};
		if (createHash('sha256').update(source).digest('hex') !== provenance.sha256)
			throw new Error('Server API snapshot does not match its source digest');
		const document = JSON.parse(source) as OpenAPI3;
		const entries = Object.entries(document.paths ?? {}).flatMap(([path, item]) =>
			Object.entries(item)
				.filter(([method]) =>
					['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'].includes(
						method
					)
				)
				.map(([method, operation]) => ({
					path,
					method: method.toUpperCase(),
					...operation
				}))
		);
		const ids = entries.map((entry) => entry.operationId);
		if (ids.some((id) => !id) || new Set(ids).size !== ids.length)
			throw new Error('API operations require unique operation IDs');
		const header =
			'// ' +
			'@' +
			'generated by server.api from resources/server-api/openapi.json. Do not edit.\n';
		const generated = await openapiTS(refineSecurityPolicyTypes(document), {
			immutable: true,
			transform(schema) {
				if (schema.format === 'binary')
					return ts.factory.createTypeReferenceNode('Uint8Array');
				return undefined;
			}
		});
		// Keep the full schema tree: annotation names can also be legitimate DTO property names.
		const runtime = document;
		const outputs = new Map([
			[types, header + astToString(generated)],
			[
				contract,
				header +
					"import type { ApiDocument } from './apiContract.js';\nexport const serverContract = " +
					JSON.stringify(runtime) +
					' as unknown as ApiDocument;\n'
			],
			[
				inventory,
				JSON.stringify(
					{
						schemaVersion: 1,
						sha256: createHash('sha256').update(source).digest('hex'),
						paths: Object.keys(document.paths ?? {}).length,
						operations: entries.map((entry) => ({
							operationId: entry.operationId,
							method: entry.method,
							path: entry.path,
							transport:
								entry.operationId === 'connectWebSocket' ? 'websocket' : 'http'
						}))
					},
					null,
					2
				) + '\n'
			]
		]);
		for (const [path, text] of outputs) {
			const target = join(outputRoot, path);
			mkdirSync(dirname(target), { recursive: true });
			writeFileSync(target, text);
		}
	}
};

/**
 * The server model requires a full family object at every fixed tuple position.
 * Its OpenAPI prefixItems currently constrain only id; items applies after the
 * prefix in JSON Schema 2020-12. Preserve the raw runtime/source snapshot, while
 * expressing the verified server-model invariant in the generated client type.
 * The privileged policy decoder independently validates every full family.
 */
export function refineSecurityPolicyTypes(document: OpenAPI3): OpenAPI3 {
	const copy = structuredClone(document);
	const root = copy as unknown as { components?: { schemas?: Record<string, unknown> } };
	const policy = root.components?.schemas?.EffectiveExamSecurityPolicy as
		| {
				properties?: {
					capabilities?: { prefixItems?: unknown[]; items?: { oneOf?: unknown[] } };
				};
		  }
		| undefined;
	const capabilities = policy?.properties?.capabilities;
	if (!capabilities?.prefixItems || !capabilities.items?.oneOf) return copy;
	const families = capabilities.items.oneOf;
	capabilities.prefixItems = capabilities.prefixItems.map((prefix) => {
		const id = (prefix as { properties?: { id?: { const?: unknown } } }).properties?.id?.const;
		const matches = families.filter(
			(family) =>
				(family as { properties?: { id?: { const?: unknown } } }).properties?.id?.const ===
				id
		);
		if (typeof id !== 'string' || matches.length !== 1)
			throw new Error('Unrecognized security policy family tuple');
		return matches[0];
	});
	return copy;
}
