export const phosphorIconsGenerator: Generator = {
	id: 'theme.phosphor-icons',
	inputs: ['package-lock.json', 'build/generators/phosphorIcons.ts'],
	committedOutputs: [output],
	buildOutputs: [],
	generate(_repository, outputRoot) {
		// The package exports no files, so its installed directory is read directly.
		const root = join(process.cwd(), 'node_modules', '@phosphor-icons', 'core');
		const version = (
			JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string }
		).version;
		const read = (weight: 'regular' | 'fill', name: string): string => {
			const file = join(
				root,
				'assets',
				weight,
				weight === 'fill' ? `${name}-fill.svg` : `${name}.svg`
			);
			const svg = readFileSync(file, 'utf8');
			if (!/^<svg [^>]*viewBox="0 0 256 256"/u.test(svg))
				throw new Error(`Unexpected Phosphor icon shape: ${weight}/${name}`);
			if (/<(?!svg|\/svg|path)/u.test(svg))
				throw new Error(`Phosphor icon is not paths only: ${name}`);
			return [...svg.matchAll(/<path d="([^"]+)"\/?>/gu)].map((match) => match[1]).join(' ');
		};
		const glyphs: Record<string, { regular: string; fill?: string }> = {};
		for (const name of regular) glyphs[name] = { regular: read('regular', name) };
		for (const name of fill) {
			const glyph = glyphs[name];
			if (glyph === undefined) throw new Error(`Fill weight without regular weight: ${name}`);
			glyph.fill = read('fill', name);
		}
		const destination = join(outputRoot, output);
		mkdirSync(dirname(destination), { recursive: true });
		writeFileSync(
			destination,
			`// Generated by theme.phosphor-icons from @phosphor-icons/core ${version}. Do not edit.\n` +
				'/*! @license Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons */\n' +
				'/** Path data on Phosphor’s 256-unit grid, drawn with `fill="currentColor"`. */\n' +
				'export const proctorIconGlyphs = ' +
				JSON.stringify(glyphs, null, '\t') +
				' as const;\n'
		);
	}
};
