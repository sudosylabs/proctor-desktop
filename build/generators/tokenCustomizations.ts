import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';
import { Ajv } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import type { Generator } from './registry.ts';

const schemaOutput = 'src/prctr/platform/theme/common/tokenCustomizationSchemas.generated.ts';
const validatorOutput = 'src/prctr/platform/theme/common/tokenCustomizationValidation.generated.js';
const declarationsOutput =
	'src/prctr/platform/theme/common/tokenCustomizationValidation.generated.d.ts';

/** Compile the copied schema once at build time; sandboxed renderers never evaluate generated code. */
export const tokenCustomizationsGenerator: Generator = {
	id: 'theme.token-customizations',
	inputs: [
		'src/prctr/platform/theme/common/colorThemeSchema.ts',
		'src/prctr/platform/theme/common/tokenCustomizationSchemas.ts',
		'src/prctr/platform/theme/common/tokenClassificationRegistry.ts',
		'src/prctr/platform/theme/common/bundledThemes.ts',
		'package-lock.json'
	],
	committedOutputs: [schemaOutput, validatorOutput, declarationsOutput],
	buildOutputs: [],
	async generate(_repository, outputRoot) {
		const result = await build({
			entryPoints: ['src/prctr/platform/theme/common/tokenCustomizationSchemas.ts'],
			bundle: true,
			write: false,
			format: 'esm',
			platform: 'node',
			target: 'node24',
			tsconfig: 'build/tsconfig.platform-foundation.json'
		});
		const source = (await import(
			`data:text/javascript;base64,${Buffer.from(result.outputFiles[0]!.text).toString('base64')}`
		)) as { getTokenCustomizationSchemas(): Record<string, object> };
		// Keep each schema's local JSON pointers rooted in that schema while relocating exact resource IDs.
		const schemas: Record<string, object> = Object.fromEntries(
			Object.entries(source.getTokenCustomizationSchemas()).map(([id, schema]) => {
				const uri = id.replace('vscode://schemas/', 'prctr-schema://themes/');
				const relocated = JSON.parse(
					JSON.stringify(schema).replaceAll('vscode://schemas/', 'prctr-schema://themes/')
				) as object;
				return [uri, { ...relocated, $id: uri }];
			})
		);
		const ajv = new Ajv({
			strict: false,
			code: { source: true, esm: true, lines: true },
			allErrors: false
		});
		ajv.addFormat(
			'color-hex',
			/^(?:#[\da-fA-F]{3}|#[\da-fA-F]{4}|#[\da-fA-F]{6}|#[\da-fA-F]{8})$/
		);
		for (const [id, schema] of Object.entries(schemas)) ajv.addSchema(schema, id);
		const generated = standaloneCode.default(ajv, {
			validateTokenColors: 'prctr-schema://themes/token-customizations',
			validateSemanticTokenColors: 'prctr-schema://themes/semantic-token-customizations'
		});
		for (const output of [schemaOutput, validatorOutput, declarationsOutput])
			mkdirSync(dirname(join(outputRoot, output)), { recursive: true });
		writeFileSync(
			join(outputRoot, schemaOutput),
			'// Generated by theme.token-customizations. Do not edit.\nexport const tokenCustomizationSchemas: Readonly<Record<string, object>> = ' +
				JSON.stringify(schemas, null, '\t') +
				';\n'
		);
		writeFileSync(
			join(outputRoot, validatorOutput),
			'// Generated by theme.token-customizations using Ajv standalone. Do not edit.\n' +
				generated
		);
		writeFileSync(
			join(outputRoot, declarationsOutput),
			'// Generated by theme.token-customizations. Do not edit.\nexport function validateTokenColors(value: unknown): boolean;\nexport function validateSemanticTokenColors(value: unknown): boolean;\n'
		);
	}
};
