import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import type { Generator } from './registry.ts';

const input = 'resources/server-api/asyncapi.json';
const provenance = 'resources/server-api/source.json';
const types = 'src/prctr/platform/serverApi/common/serverEvents.generated.ts';
const schemas = 'src/prctr/platform/serverApi/node/serverRealtimeContract.generated.ts';

type JsonObject = Record<string, unknown>;

/**
 * The copies of one server event, keyed by how they are delivered: the subscription action a
 * resource-delivered copy requires, or {@link USER_DELIVERY} for a copy addressed to one User.
 * Each maps to its payload schema, or `null` for a copy without data. The server sends one fact
 * to two audiences under one name when their payload or authorization differs.
 */
type EventVariants = Map<string, string | null>;
const USER_DELIVERY = '@user';

export const serverRealtimeGenerator: Generator = {
	id: 'server.realtime',
	inputs: [input, provenance, 'build/generators/serverRealtime.ts'],
	committedOutputs: [types, schemas],
	buildOutputs: [],
	async generate(repository, outputRoot) {
		const source = repository.read(input);
		const recorded = JSON.parse(repository.read(provenance)) as { asyncapiSha256?: string };
		if (createHash('sha256').update(source).digest('hex') !== recorded.asyncapiSha256)
			throw new Error('Server realtime snapshot does not match its source digest');
		const document = JSON.parse(source) as JsonObject;
		if (document.asyncapi !== '3.0.0')
			throw new Error('Expected the Proctor AsyncAPI 3.0 contract');
		const components = object(document.components, 'components');
		const messages = object(components.messages, 'components.messages');
		const named = object(components.schemas, 'components.schemas');
		const events = eventCatalog(messages);
		const header =
			'// ' +
			'@' +
			'generated by server.realtime from resources/server-api/asyncapi.json. Do not edit.\n';
		const generated = await openapiTS(
			{
				openapi: '3.1.0',
				info: { title: 'Proctor realtime payloads', version: '1' },
				paths: {},
				components: { schemas: named }
			} as unknown as OpenAPI3,
			{ immutable: true }
		);
		const names = [...events.keys()].sort();
		const render = (value: (data: string | null) => string) =>
			names
				.map((name) => {
					const variants = [...events.get(name)!.entries()].sort(([x], [y]) =>
						x < y ? -1 : 1
					);
					const body = variants
						.map(([delivery, data]) => `${JSON.stringify(delivery)}: ${value(data)}`)
						.join('; ');
					return `\t${JSON.stringify(name)}: { ${body} };`;
				})
				.join('\n');
		const catalog = render((data) => JSON.stringify(data))
			.replace(/; \}/gu, ' }')
			.replace(/; /gu, ', ')
			.replace(/ \};$/gmu, ' },');
		const dataMap = render((data) =>
			data === null ? 'undefined' : `components['schemas'][${JSON.stringify(data)}]`
		);
		const outputs = new Map([
			[
				types,
				header +
					astToString(generated) +
					`\n/** A copy addressed to one User, delivered without a subscription. */\nexport const USER_DELIVERY = ${JSON.stringify(USER_DELIVERY)};\n\n` +
					'/** Each server event by delivery: a subscription action, or USER_DELIVERY, to its payload schema (null without data). */\n' +
					`export const serverEventCatalog = {\n${catalog}\n} as const;\n\n` +
					'/** The payload of each server event by delivery, `undefined` for a copy without data. */\n' +
					`export interface ServerEventVariants {\n${dataMap}\n}\n`
			],
			[
				schemas,
				header +
					'export const serverRealtimeSchemas = ' +
					JSON.stringify(stripAnnotations(named)) +
					' as const;\n'
			]
		]);
		for (const [path, text] of outputs) {
			const target = join(outputRoot, path);
			mkdirSync(dirname(target), { recursive: true });
			writeFileSync(target, text);
		}
	}
};

function eventCatalog(messages: JsonObject): Map<string, EventVariants> {
	const events = new Map<string, EventVariants>();
	for (const [id, raw] of Object.entries(messages)) {
		const message = object(raw, id);
		const tags = (message.tags as { name?: unknown }[] | undefined) ?? [];
		if (!tags.some((tag) => tag.name === 'event')) continue;
		const narrowing = object(
			(object(message.payload, `${id}.payload`).allOf as unknown[] | undefined)?.[1],
			`${id}.payload.allOf[1]`
		);
		const properties = object(narrowing.properties, `${id} properties`);
		const name = object(properties.event, `${id} event`).const;
		if (typeof name !== 'string') throw new Error(`${id} has no event name`);
		const action = (properties.action as { const?: unknown } | undefined)?.const;
		if (action !== undefined && (typeof action !== 'string' || action === USER_DELIVERY))
			throw new Error(`${id} has an invalid action`);
		// A copy with an action needs a subscription, even when the server narrows it to one
		// User's connections; a copy without one reaches every connection of its User.
		const required = (narrowing.required as unknown[] | undefined) ?? [];
		if (action === undefined && !required.includes('user_id'))
			throw new Error(`${id} is neither subscribed to nor addressed to one User`);
		const ref = (properties.data as { $ref?: unknown } | undefined)?.$ref;
		const data = typeof ref === 'string' ? ref.replace(/^#\/components\/schemas\//u, '') : null;
		if (data !== null && data.includes('/'))
			throw new Error(`${id} has an unsupported payload`);
		const delivery = action ?? USER_DELIVERY;
		let variants = events.get(name);
		if (!variants) events.set(name, (variants = new Map()));
		if (variants.has(delivery) && variants.get(delivery) !== data)
			throw new Error(`${name} has two payloads for ${delivery}`);
		variants.set(delivery, data);
	}
	return events;
}

const annotations = new Set(['description', 'title', 'examples', '$comment']);
function stripAnnotations(value: unknown): unknown {
	if (Array.isArray(value)) return value.map(stripAnnotations);
	if (typeof value !== 'object' || value === null) return value;
	return Object.fromEntries(
		Object.entries(value)
			.filter(
				([key, child]) =>
					!annotations.has(key) || (key !== 'examples' && typeof child === 'object')
			)
			.map(([key, child]) => [key, stripAnnotations(child)])
	);
}

function object(value: unknown, where: string): JsonObject {
	if (typeof value !== 'object' || value === null || Array.isArray(value))
		throw new Error(`${where} must be an object`);
	return value as JsonObject;
}
